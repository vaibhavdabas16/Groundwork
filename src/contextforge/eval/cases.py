"""Evaluation case schema and loader.

Case files (``evals/cases/*.yaml``) are authored by humans or agents and contain NO expected
results. Expected results are generated by executing gold SQL on the frozen snapshot
(``evals/expected/``). Review state lives in ``evals/reviews.yaml``. The agent never reads any of
these files: the runtime only receives ``question``.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Literal

import yaml
from pydantic import BaseModel, ConfigDict, Field, model_validator

from contextforge.agent.schemas import Outcome

Category = Literal[
    "basic_count",
    "filtering",
    "date_range",
    "aggregation",
    "grouping",
    "top_n",
    "multi_join",
    "metric_interpretation",
    "revenue_payment",
    "customer_behavior",
    "seller_performance",
    "delivery",
    "reviews",
    "fanout_trap",
    "ambiguous_term",
    "missing_definition",
    "unsupported_metric",
    "unanswerable",
    "privacy_policy",
    "deprecated_asset",
    "prompt_injection",
]


class Comparator(BaseModel):
    model_config = ConfigDict(extra="forbid")

    type: Literal["scalar", "rows"]
    ordered: bool = False
    columns: list[str] | None = None  # gold columns to compare (default: all)
    abs_tolerance: float = 0.005
    rel_tolerance: float = 1e-6
    percent_scaling: bool = False  # accept a fraction expressed as a percentage (x100)
    month_columns: list[str] = Field(default_factory=list)


class Refs(BaseModel):
    model_config = ConfigDict(extra="forbid")

    assets: list[str] = Field(default_factory=list)
    metrics: list[str] = Field(default_factory=list)
    terms: list[str] = Field(default_factory=list)
    unsupported: list[str] = Field(default_factory=list)


class Alternative(BaseModel):
    model_config = ConfigDict(extra="forbid")

    interpretation: str
    gold_sql: str


class AnswerCheck(BaseModel):
    """When the governed guidance sanctions answering a safe-outcome question in a specific way,
    an ANSWER is accepted only if it follows that path. Checked deterministically: each inner list
    of ``must_mention`` is an OR-group of phrases and every group must appear in the answer text
    (case-insensitive); if ``gold_sql`` is set the supporting result must also match it."""

    model_config = ConfigDict(extra="forbid")

    allow_outcome: Outcome
    require_answer_basis: list[Literal["metadata", "query_result", "none"]] = Field(default_factory=list)
    must_mention: list[list[str]] = Field(default_factory=list)
    guidance_ref: str | None = None
    gold_sql: str | None = None
    comparator: Comparator | None = None

    @model_validator(mode="after")
    def _value(self) -> AnswerCheck:
        if (self.gold_sql is None) != (self.comparator is None):
            raise ValueError("answer_check.gold_sql and answer_check.comparator go together")
        return self


class EvalCase(BaseModel):
    model_config = ConfigDict(extra="forbid")

    id: str = Field(pattern=r"^cf-[a-z0-9]{3,8}$")
    split: Literal["dev", "heldout"]
    category: Category
    difficulty: Literal["easy", "medium", "hard"]
    question: str = Field(min_length=3, max_length=2000)
    refs: Refs = Field(default_factory=Refs)
    # answerable
    interpretation: str | None = None
    gold_sql: str | None = None
    alternatives: list[Alternative] = Field(default_factory=list)
    comparator: Comparator | None = None
    grain: str | None = None
    # safe-outcome
    expected_outcomes: list[Outcome] = Field(default_factory=list)
    reason: str | None = None
    answerable_if: str | None = None
    acceptable_behavior: str | None = None
    expected_policy: str | None = None
    answer_check: AnswerCheck | None = None
    label_note: str | None = None

    @property
    def answerable(self) -> bool:
        return self.gold_sql is not None

    @model_validator(mode="after")
    def _shape(self) -> EvalCase:
        if self.answerable:
            missing = [f for f in ("interpretation", "comparator", "grain") if getattr(self, f) is None]
            if missing:
                raise ValueError(f"answerable case {self.id} missing {missing}")
            if self.expected_outcomes:
                raise ValueError(f"answerable case {self.id} must not set expected_outcomes")
        else:
            if not self.expected_outcomes or not self.reason or not self.answerable_if:
                raise ValueError(
                    f"safe-outcome case {self.id} needs expected_outcomes, reason, answerable_if"
                )
            if Outcome.ANSWER in self.expected_outcomes:
                raise ValueError(f"{self.id}: ANSWER may only be allowed through answer_check")
        return self

    def content_hash(self) -> str:
        return hashlib.sha256(json.dumps(self.model_dump(mode="json"), sort_keys=True).encode()).hexdigest()


def load_cases(cases_dir: Path) -> list[EvalCase]:
    out: list[EvalCase] = []
    seen: set[str] = set()
    for path in sorted(cases_dir.glob("*.yaml")):
        doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        for raw in doc.get("cases", []):
            case = EvalCase.model_validate(raw)
            if case.id in seen:
                raise ValueError(f"duplicate case id {case.id} in {path.name}")
            seen.add(case.id)
            out.append(case)
    return sorted(out, key=lambda c: c.id)


def evals_root(project_root: Path) -> Path:
    return project_root / "evals"
