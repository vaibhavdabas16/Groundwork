"""Isolated query worker. Runs as a separate, killable OS process (``python -I -m ...``).

Protocol: one JSON request on stdin, one JSON response on stdout, then exit. The worker:

* opens ONLY the serving database, read-only;
* disables external access (file system / network / COPY / ATTACH), extension auto-install/load,
  community extensions, then locks the configuration so SQL cannot change it;
* applies memory and thread limits;
* on POSIX additionally applies RLIMIT_AS / RLIMIT_CPU (the parent always enforces a wall-clock
  timeout by killing this process);
* fetches at most ``max_rows + 1`` rows and stops serialising once ``max_result_bytes`` is reached.

The SQL it receives has already been validated and regenerated by the trusted parent.
"""

from __future__ import annotations

import datetime as dt
import decimal
import json
import re
import sys
import time
import uuid
from typing import Any


def _apply_os_limits(memory_bytes: int | None, cpu_seconds: int | None) -> None:
    if sys.platform == "win32":
        return  # no RLIMIT on Windows; the parent's wall-clock kill is the hard bound
    import resource

    if memory_bytes:
        resource.setrlimit(resource.RLIMIT_AS, (memory_bytes, memory_bytes))
    if cpu_seconds:
        resource.setrlimit(resource.RLIMIT_CPU, (cpu_seconds, cpu_seconds + 1))


def _jsonable(value: Any) -> Any:
    if value is None or isinstance(value, (bool, int, str)):
        return value
    if isinstance(value, float):
        return value if value == value and value not in (float("inf"), float("-inf")) else None
    if isinstance(value, decimal.Decimal):
        return float(value) if abs(value) < decimal.Decimal(2**53) else str(value)
    if isinstance(value, (dt.datetime, dt.date, dt.time)):
        return value.isoformat()
    if isinstance(value, uuid.UUID):
        return str(value)
    if isinstance(value, (list, tuple)):
        return [_jsonable(v) for v in value]
    if isinstance(value, dict):
        return {str(k): _jsonable(v) for k, v in value.items()}
    return str(value)


_QUOTED = re.compile(r"(\"[^\"]*\"|'[^']*')")


def sanitize_error(message: str) -> str:
    """First line only, quoted fragments (paths, literal values) redacted."""
    first = message.strip().splitlines()[0] if message.strip() else "error"
    return _QUOTED.sub("<redacted>", first)[:300]


def _estimated_rows(plan_json: str) -> int | None:
    try:
        tree = json.loads(plan_json)
    except ValueError:
        return None
    best: int | None = None

    def walk(node: Any) -> None:
        nonlocal best
        if isinstance(node, dict):
            for k, v in node.items():
                if "cardinality" in k.lower():
                    try:
                        n = int(str(v).replace(",", "").lstrip("~"))
                    except ValueError:
                        n = None
                    if n is not None and (best is None or n > best):
                        best = n
                else:
                    walk(v)
        elif isinstance(node, list):
            for x in node:
                walk(x)

    walk(tree)
    return best


def run(req: dict[str, Any]) -> dict[str, Any]:
    import duckdb

    config = {
        "enable_external_access": False,
        "autoload_known_extensions": False,
        "autoinstall_known_extensions": False,
        "allow_community_extensions": False,
        "allow_unsigned_extensions": False,
        "allow_persistent_secrets": False,
        "memory_limit": req["memory_limit"],
        "threads": int(req["threads"]),
        "max_temp_directory_size": "0B",
        "lock_configuration": True,
    }
    started = time.perf_counter()
    con = duckdb.connect(req["db_path"], read_only=True, config=config)
    try:
        explain_json = con.execute("EXPLAIN (FORMAT JSON) " + req["sql"]).fetchall()
        est = _estimated_rows(explain_json[0][1]) if explain_json else None
        if req["mode"] == "explain":
            plan_text = con.execute("EXPLAIN " + req["sql"]).fetchall()
            return {
                "ok": True,
                "plan": plan_text[0][1] if plan_text else "",
                "estimated_max_cardinality": est,
                "elapsed_ms": round((time.perf_counter() - started) * 1000, 2),
            }
        max_cost = req.get("max_cost_estimated_rows")
        if max_cost and est is not None and est > max_cost:
            return {
                "ok": False,
                "error_code": "cost_limit_exceeded",
                "error": f"estimated intermediate cardinality {est} exceeds limit {max_cost}",
                "estimated_max_cardinality": est,
            }
        cur = con.execute(req["sql"])
        columns = [d[0] for d in cur.description or []]
        types = [str(d[1]) for d in cur.description or []]
        max_rows = int(req["max_rows"])
        raw_rows = cur.fetchmany(max_rows + 1)
        truncated = len(raw_rows) > max_rows
        rows: list[list[Any]] = []
        size = 0
        byte_truncated = False
        for r in raw_rows[:max_rows]:
            row = [_jsonable(v) for v in r]
            size += len(json.dumps(row, default=str))
            if size > int(req["max_result_bytes"]):
                byte_truncated = True
                break
            rows.append(row)
        return {
            "ok": True,
            "columns": columns,
            "column_types": types,
            "rows": rows,
            "row_count": len(rows),
            "truncated": truncated or byte_truncated,
            "truncation_reason": "max_result_bytes"
            if byte_truncated
            else ("max_rows" if truncated else None),
            "estimated_max_cardinality": est,
            "elapsed_ms": round((time.perf_counter() - started) * 1000, 2),
        }
    except duckdb.Error as exc:
        return {
            "ok": False,
            "error_code": "execution_error",
            "error": f"{type(exc).__name__}: {sanitize_error(str(exc))}",
        }
    finally:
        con.close()


def main() -> None:
    req = json.loads(sys.stdin.read())
    _apply_os_limits(req.get("os_memory_bytes"), req.get("os_cpu_seconds"))
    try:
        resp = run(req)
    except Exception as exc:
        resp = {
            "ok": False,
            "error_code": "worker_error",
            "error": f"{type(exc).__name__}: {sanitize_error(str(exc))}",
        }
    sys.stdout.write(json.dumps(resp))
    sys.stdout.flush()


if __name__ == "__main__":
    main()
